#include "runtime.h"

/* Byte loops deliberately retain optnone: no recursive libc lowering. */
static const char BUILTINS_MEMORY_IR[] =
    "\n"
    "define ptr @memcpy(ptr %dst, ptr %src, SIZE %n) #0 {\n"
    "entry:\n"
    "  br label %test\n"
    "test:\n"
    "  %i = phi SIZE [ 0, %entry ], [ %next, %copy ]\n"
    "  %done = icmp eq SIZE %i, %n\n"
    "  br i1 %done, label %end, label %copy\n"
    "copy:\n"
    "  %s = getelementptr i8, ptr %src, SIZE %i\n"
    "  %d = getelementptr i8, ptr %dst, SIZE %i\n"
    "  %v = load i8, ptr %s, align 1\n"
    "  store i8 %v, ptr %d, align 1\n"
    "  %next = add SIZE %i, 1\n"
    "  br label %test\n"
    "end:\n"
    "  ret ptr %dst\n"
    "}\n"
    "define ptr @memset(ptr %dst, i32 %value, SIZE %n) #0 {\n"
    "entry:\n"
    "  %v = trunc i32 %value to i8\n"
    "  br label %test\n"
    "test:\n"
    "  %i = phi SIZE [ 0, %entry ], [ %next, %set ]\n"
    "  %done = icmp eq SIZE %i, %n\n"
    "  br i1 %done, label %end, label %set\n"
    "set:\n"
    "  %d = getelementptr i8, ptr %dst, SIZE %i\n"
    "  store i8 %v, ptr %d, align 1\n"
    "  %next = add SIZE %i, 1\n"
    "  br label %test\n"
    "end:\n"
    "  ret ptr %dst\n"
    "}\n"
    "define ptr @memmove(ptr %dst, ptr %src, SIZE %n) #0 {\n"
    "entry:\n"
    "  %forward = icmp ule ptr %dst, %src\n"
    "  br i1 %forward, label %fwd, label %test\n"
    "fwd:\n"
    "  %unused = call ptr @memcpy(ptr %dst, ptr %src, SIZE %n)\n"
    "  br label %end\n"
    "test:\n"
    "  %i = phi SIZE [ %n, %entry ], [ %prev, %copy ]\n"
    "  %done = icmp eq SIZE %i, 0\n"
    "  br i1 %done, label %end, label %copy\n"
    "copy:\n"
    "  %prev = sub SIZE %i, 1\n"
    "  %s = getelementptr i8, ptr %src, SIZE %prev\n"
    "  %d = getelementptr i8, ptr %dst, SIZE %prev\n"
    "  %v = load i8, ptr %s, align 1\n"
    "  store i8 %v, ptr %d, align 1\n"
    "  br label %test\n"
    "end:\n"
    "  ret ptr %dst\n"
    "}\n"
    "define i32 @memcmp(ptr %lhs, ptr %rhs, SIZE %n) #0 {\n"
    "entry:\n"
    "  br label %test\n"
    "test:\n"
    "  %i = phi SIZE [ 0, %entry ], [ %next, %equal ]\n"
    "  %done = icmp eq SIZE %i, %n\n"
    "  br i1 %done, label %end, label %compare\n"
    "compare:\n"
    "  %l = getelementptr i8, ptr %lhs, SIZE %i\n"
    "  %r = getelementptr i8, ptr %rhs, SIZE %i\n"
    "  %a = load i8, ptr %l, align 1\n"
    "  %b = load i8, ptr %r, align 1\n"
    "  %az = zext i8 %a to i32\n"
    "  %bz = zext i8 %b to i32\n"
    "  %diff = sub i32 %az, %bz\n"
    "  %same = icmp eq i32 %diff, 0\n"
    "  br i1 %same, label %equal, label %different\n"
    "equal:\n"
    "  %next = add SIZE %i, 1\n"
    "  br label %test\n"
    "different:\n"
    "  ret i32 %diff\n"
    "end:\n"
    "  ret i32 0\n"
    "}\n"
    "@bcmp = alias i32 (ptr, ptr, SIZE), ptr @memcmp\n"
    "attributes #0 = { noinline nounwind optnone \"no-builtins\" }\n";

char *builtins_memory_ir(Target t) {
  const char *size =
      in_target_inventory("arm x86 wasm32", t.arch) ? "i32" : "i64";
  return str_replace(BUILTINS_MEMORY_IR, "SIZE", size);
}
